const cachePaths = [
  "src/main/resources/translations_cache.json",
  "target/classes/translations_cache.json"
];

cachePaths.forEach(cachePath => {
  if (fs.existsSync(cachePath)) {
    const cache = JSON.parse(fs.readFileSync(cachePath, 'utf8'));
    let addedCount = 0;
    
    // Add translations from dictionary
    Object.keys(dictionary).forEach(lang => {
      Object.keys(dictionary[lang]).forEach(engText => {
        const key = `${lang}:${engText.trim()}`;
        if (!cache[key]) {
          cache[key] = dictionary[lang][engText];
          addedCount++;
        }
      });
    });

    fs.writeFileSync(cachePath, JSON.stringify(cache, null, 2), 'utf8');
    console.log(`Successfully added ${addedCount} fallback translation mappings to ${cachePath}`);
  } else {
    console.log(`Cache file does not exist at ${cachePath}`);
  }
});
